export const sdkCredentialTelemetryReasons = [
  "selected",
  "unsupported_operation",
  "missing_token",
  "malformed_token",
  "expired_token",
  "old_scope",
  "branch_override",
] as const;

export type SdkCredentialTelemetryOperation = (typeof sdkCredentialTelemetryOperations)[number];
export type SdkCredentialTelemetryReason = (typeof sdkCredentialTelemetryReasons)[number];

const operations = new Set<string>(sdkCredentialTelemetryOperations);
const reasons = new Set<string>(sdkCredentialTelemetryReasons);

export function isSdkCredentialTelemetryOperation(
  value: unknown
): value is SdkCredentialTelemetryOperation {
  return typeof value === "string" && operations.has(value);
}

export function isSdkCredentialTelemetryReason(
  value: unknown
): value is SdkCredentialTelemetryReason {
  return typeof value === "string" && reasons.has(value);
}
